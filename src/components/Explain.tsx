import { useEffect, useRef, useState, type ReactNode } from 'react';
import { AlertTriangle, CheckCircle2, Cpu, Info, ListChecks, Sparkles, XCircle } from 'lucide-react';
import { EXPLAIN_URL } from '../lib/ic';
import { fetchExplain } from '../lib/explain';
import { Button, Card, CardHeader, ErrorBox, Spinner, cx } from './ui';

type Data = {
  does: string[];
  onchain: string[];
  consistency: 'match' | 'partial' | 'mismatch';
  consistency_notes: string[];
  risks: string[];
  checks: string[];
};
type Res = { data: Data | null; text: string; model: string; cached: boolean; created: string };

const tone = {
  neutral: 'border-line bg-fg/[0.02]',
  accent: 'border-accent/25 bg-accent/[0.05]',
  yes: 'border-yes/25 bg-yes/[0.06]',
  warn: 'border-warn/30 bg-warn/[0.07]',
  no: 'border-no/30 bg-no/[0.06]',
} as const;
const iconTone = { neutral: 'text-muted', accent: 'text-accent', yes: 'text-yes', warn: 'text-warn', no: 'text-no' } as const;

function Block({ t, icon: Icon, title, items }: { t: keyof typeof tone; icon: typeof Info; title: ReactNode; items: string[] }) {
  if (!Array.isArray(items) || !items.length) return null;
  return (
    <div className={cx('rounded-lg border p-3.5', tone[t])}>
      <div className={cx('mb-1.5 flex items-center gap-2 text-xs font-semibold', iconTone[t])}>
        <Icon className="size-3.5" />
        {title}
      </div>
      <ul className="space-y-1 text-sm leading-relaxed text-fg/90">
        {items.map((x, i) => (
          <li key={i} className="flex gap-2">
            <span className="mt-2 size-1 shrink-0 rounded-full bg-current opacity-40" />
            <span>{x}</span>
          </li>
        ))}
      </ul>
    </div>
  );
}

const verdict = {
  match: { t: 'yes', icon: CheckCircle2, label: 'Summary matches the on-chain action' },
  partial: { t: 'warn', icon: AlertTriangle, label: 'Summary makes claims the payload does not confirm' },
  mismatch: { t: 'no', icon: XCircle, label: 'Summary contradicts the on-chain action' },
} as const;

export type ExplainState = { res?: Res; error?: unknown; loading: boolean; run: () => void };

export function useExplain(id: bigint): ExplainState {
  const [res, setRes] = useState<Res>();
  const [error, setError] = useState<unknown>();
  const [loading, setLoading] = useState(!!EXPLAIN_URL);
  const seq = useRef(0);

  const run = async () => {
    if (!EXPLAIN_URL) return;
    const s = ++seq.current;
    setLoading(true);
    setError(undefined);
    setRes(undefined);
    try {
      const r = await fetchExplain(id);
      if (s === seq.current) setRes(r);
    } catch (e) {
      if (s === seq.current) setError(e);
    } finally {
      if (s === seq.current) setLoading(false);
    }
  };

  useEffect(() => {
    run();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [id]);

  return { res, error, loading, run };
}

export const verdictOf = (st: ExplainState) =>
  st.res?.data ? { consistency: st.res.data.consistency, risks: st.res.data.risks?.length ?? 0 } : undefined;

export function ExplainBody({ st }: { st: ExplainState }) {
  const { res, error, loading, run } = st;
  const d = res?.data;
  const v = d && (verdict[d.consistency] ?? verdict.partial);
  const txt = res && !d ? (typeof res.text === 'string' ? res.text : JSON.stringify(res.text)) : '';
  return (
    <div className="space-y-3">
      {loading && <Spinner label="Explaining… (first time ~10 s, then instant)" />}
      {error ? <ErrorBox error={error} onRetry={run} /> : null}
      {d && v && (
        <>
          <Block t="neutral" icon={Info} title="What it does" items={d.does} />
          <Block t="accent" icon={Cpu} title="What actually changes" items={d.onchain} />
          <Block t={v.t} icon={v.icon} title={v.label} items={d.consistency_notes} />
          <Block t="no" icon={AlertTriangle} title="Risks" items={d.risks} />
          <Block t="warn" icon={ListChecks} title="Check before voting" items={d.checks} />
        </>
      )}
      {txt && <div className="whitespace-pre-wrap text-sm leading-relaxed text-fg/90">{txt}</div>}
      {res && (
        <div className="text-[11px] text-muted">
          AI explanation · {res.model.split('/').pop()} · may contain mistakes
        </div>
      )}
    </div>
  );
}

export function Explain({ st }: { st: ExplainState }) {
  if (!EXPLAIN_URL) return null;
  return (
    <Card>
      <CardHeader
        title={
          <span className="inline-flex items-center gap-2">
            <Sparkles className="size-4 text-accent" /> Explanation
          </span>
        }
        sub="In plain words, generated by AI from the on-chain action — can be wrong"
        right={st.error && !st.loading ? <Button onClick={st.run}>Retry</Button> : undefined}
      />
      <div className="px-5 py-4">
        <ExplainBody st={st} />
      </div>
    </Card>
  );
}
